"""Generate a Russian TTS audio guide for Chureito Pagoda (~3 min)."""
from gtts import gTTS
from pathlib import Path

text_ru = """
Пагода Чурейто. Один из самых узнаваемых символов Японии.

Представьте себе: вы поднимаетесь по четырёмстам тридцати ступеням древней лестницы,
окружённой вековыми криптомериями. И вдруг, за поворотом, открывается вид, который
навсегда остаётся в памяти — красная пятиярусная пагода на фоне величественной горы Фудзи.

Пагода Чурейто расположена в городе Фудзиёсида, в префектуре Яманаси.
Она входит в состав синтоистского святилища Арасияма — Асама, основанного ещё в
семьсот восьмом году нашей эры. Само слово «Чурейто» означает «башня, посвящённая душам»,
и изначально пагода была возведена как мемориал воинам, павшим за Японию.

Нынешнее здание пагоды было построено в тысяча девятьсот пятьдесят восьмом году.
Несмотря на то, что постройка относительно молодая, она органично вписывается в
окружающий пейзаж и воспринимается как нечто вечное.

Лучшее время для посещения — ранняя весна, когда цветёт сакура.
В этот период вишнёвые деревья обрамляют ступени и пагоду нежно-розовым цветом,
создавая один из самых фотографируемых видов в мире.
Не менее красиво здесь осенью, когда листья окрашиваются в огненные тона,
и в ясные дни, когда вершина Фудзи покрыта снегом.

Чтобы добраться до пагоды, нужно доехать до станции Фудзиёсида на электричке,
а затем пройти пешком около двадцати минут до начала лестницы.
Сам подъём занимает от пятнадцати до двадцати минут в зависимости от вашего темпа.
Вход на территорию святилища и к пагоде — бесплатный.

Совет путешественнику: приходите рано утром, до девяти часов. В это время здесь
значительно меньше туристов, свет мягче, и виды на Фудзи особенно чёткие.
Возьмите с собой воду и удобную обувь — ступени крутые и их много.

Пагода Чурейто — это не просто туристическая достопримечательность.
Это место, где история, природа и духовность Японии соединяются в одном образе.
Стоя здесь, понимаешь, почему японцы так трепетно относятся к красоте мгновения —
моно-но аварэ — печальному очарованию преходящего.

Удачного вам путешествия.
"""

out_dir = Path("assets/audio")
out_dir.mkdir(parents=True, exist_ok=True)
out_path = out_dir / "chureito_ru.mp3"

tts = gTTS(text=text_ru.strip(), lang="ru", slow=False)
tts.save(str(out_path))
print(f"Saved: {out_path}  ({out_path.stat().st_size // 1024} KB)")

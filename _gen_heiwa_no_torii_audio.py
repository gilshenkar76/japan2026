"""Generate a Russian TTS voice guide for Heiwa no Torii, Lake Ashi (~3 min).
Keep TEXT as continuous flowing sentences with NO blank lines between
paragraphs — edge-tts inserts an audible extra pause at every blank line."""
import asyncio, pathlib, edge_tts

VOICE = "ru-RU-DmitryNeural"

TEXT = (
"Тории Хэйва, врата мира. Одно из самых узнаваемых мест Хаконэ — красные ворота, стоящие прямо в водах озера Аси. "
"Эти тории являются частью синтоистского святилища Хаконэ Дзиндзя, расположенного неподалёку в лесу у подножия горы. "
"Само святилище было основано более тысячи двухсот лет назад и издавна почиталось как место, охраняющее путников и обеспечивающее удачу в делах. "
"Ворота в озере были возведены значительно позже, в честь окончания Второй мировой войны, поэтому их называют вратами мира. "
"В ясную погоду отсюда открывается один из самых красивых видов во всей Японии: красные тории на фоне синей воды озера, а вдалеке — заснеженная вершина горы Фудзи. "
"Именно поэтому это место считается одной из самых фотографируемых точек региона Хаконэ. "
"Лучшее время для съёмки — раннее утро, когда вода спокойна, туристов ещё немного, а воздух особенно прозрачен. "
"Многие путешественники заходят прямо в воду у ворот, чтобы сделать снимок как можно ближе к тории — это стало своеобразной традицией. "
"Совет путешественнику: если вы планируете фотографироваться у самих ворот, наденьте обувь, которую не жалко немного намочить. "
"Прогулка через лес от главного святилища к воротам занимает всего несколько минут и сама по себе очень атмосферна, среди высоких криптомерий. "
"Тории Хэйва — символ мира и спокойствия, встречающий гостей Хаконэ у самой кромки воды."
)

async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Heiwa no Torii.mp3"
    comm = edge_tts.Communicate(TEXT.strip(), VOICE)
    await comm.save(str(out_path))
    print(f"Saved: {out_path}  ({out_path.stat().st_size / 1024:.0f} KB)")

asyncio.run(main())

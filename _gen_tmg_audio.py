"""Generate a Russian TTS voice guide for Tokyo Metropolitan Government Building (~3 min)."""
import asyncio, pathlib, edge_tts

VOICE = "ru-RU-DmitryNeural"

TEXT = """
Здание правительства Токио. Один из самых известных и доступных смотровых
небоскрёбов города.

Построено оно было в тысяча девятьсот девяносто первом году по проекту
знаменитого японского архитектора Кэндзо Тангэ. Две башни-близнецы высотой
двести сорок три метра долгие годы были самым высоким зданием Токио и до
сих пор остаются одним из символов района Синдзюку.

На сорок пятом этаже каждой из башен находится смотровая площадка, открытая
для всех желающих, на высоте двести два метра над улицей. Отсюда открывается
панорамный вид на весь Токио: небоскрёбы Синдзюку, горы Окутама вдалеке,
а в особенно ясные дни — и самая знаменитая гора Японии, Фудзи.

Вход на смотровую площадку полностью бесплатный, и это одна из причин,
почему она так популярна среди путешественников. Рекомендуется приходить
рано утром, сразу после открытия, чтобы избежать очередей и толп туристов,
которые собираются здесь во второй половине дня.

Помимо вида, в здании есть небольшой сувенирный магазин и уютное кафе —
хорошее место, чтобы немного отдохнуть перед продолжением дня.

Совет путешественнику: если небо ясное, стоит заранее проверить прогноз
погоды — гора Фудзи хорошо видна только в дни без облачности, чаще всего
зимой и в прохладные осенние дни.

Эта смотровая площадка — прекрасная возможность начать день в Токио с
широкого взгляда на весь город, прежде чем отправиться исследовать его
улицу за улицей.

Приятного путешествия.
"""

async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Tokyo Metropolitan Government Building.mp3"
    comm = edge_tts.Communicate(TEXT.strip(), VOICE)
    await comm.save(str(out_path))
    print(f"Saved: {out_path}  ({out_path.stat().st_size / 1024:.0f} KB)")

asyncio.run(main())

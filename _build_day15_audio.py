def build_guide(filename: str, phrases: list[str]) -> None:
    OUT_DIR.mkdir(exist_ok=True)
    output = OUT_DIR / filename
    with tempfile.TemporaryDirectory() as temp_dir:
        wav_path = pathlib.Path(temp_dir) / "guide.wav"
        render_phrases(phrases, wav_path)
        subprocess.run(
            [
                imageio_ffmpeg.get_ffmpeg_exe(),
                "-y",
                "-i",
                str(wav_path),
                "-codec:a",
                "libmp3lame",
                "-b:a",
                "96k",
                str(output),
            ],
            check=True,
            capture_output=True,
        )
    print(f"Saved: {output} ({output.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    for guide_filename, guide_phrases in GUIDES.items():
        build_guide(guide_filename, guide_phrases)
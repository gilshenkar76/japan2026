"""Professional Russian tour-guide narration for Lake Kawaguchi Maple Corridor (Momiji Kairo).
Generates mp3/Lake Kawaguchi.mp3 using edge-tts, ru-RU-DmitryNeural voice, regular speed.
"""
import asyncio
import edge_tts

VOICE = "ru-RU-DmitryNeural"
OUT = "mp3/Lake Kawaguchi.mp3"

TEXT = """
Добро пожаловать в Момидзи Кайро — Кленовый коридор на берегу озера Кавагути,
одно из самых знаменитых осенних мест региона Фудзи Го-ко, Пяти озёр Фудзи.

Немного истории. Озеро Кавагути образовалось много веков назад в результате
извержений вулкана Фудзи, когда потоки лавы перекрыли долину и создали естественную
плотину. Так возникла целая цепь из пяти озёр у подножия горы. Кавагути — самое
известное и самое доступное из них, а с восемнадцатого века эти места воспевали
японские поэты и художники, включая мастера гравюры Кацусику Хокусая, писавшего
знаменитую серию видов Фудзи именно с этого ракурса.

Аллея, по которой вы сейчас идёте, была высажена муниципалитетом города Фудзикавагутико
в тысяча девятьсот пятидесятые годы — около пятисот кленов момидзи и вязов кэяки
посадили специально, чтобы создать туннель из листвы вдоль воды. С тех пор каждую
осень, обычно с начала по конец ноября, коридор превращается в главный магнит региона
для японской традиции момидзигари — буквально охоты за красными листьями.

В отличие от европейского отношения к природе как к чему-то неизменному, японская
эстетика ценит именно мимолётность красоты: сакуру весной, зелень летом, багряные
клёны осенью и снег зимой. Каждая перемена напоминает о быстротечности момента,
и это философское понятие называется моно-но аварэ — очарование вещей.

Обратите внимание на композицию перед вами: красные и оранжевые кроны кленов,
спокойная гладь озера Кавагути и гора Фудзи на заднем плане — сочетание,
которое японцы считают одним из красивейших пейзажных видов страны.
В вечерние часы, когда в парке включают декоративную подсветку,
листва словно светится изнутри, а её отражение в воде создаёт почти зеркальную симметрию.

С практической точки зрения: коридор тянется примерно на девятьсот метров
вдоль северного берега озера, рядом расположены смотровые площадки, кафе
и сувенирные лавки, а лучшее время для фотографий — раннее утро или час перед закатом,
когда свет мягкий, а туристов меньше.

Постойте здесь немного. Прислушайтесь к шороху листьев и лёгкому ветру с озера.
Именно ради этого ощущения — тишины, цвета и присутствия горы Фудзи — сюда
приезжают путешественники со всей Японии уже более полувека.

Стоит знать и о сезонности: пик окраски листвы обычно приходится на первую-вторую
неделю ноября, но точные даты каждый год немного смещаются в зависимости от погоды,
поэтому местные туристические службы публикуют актуальный прогноз окраски листьев —
момидзи дзёухо — уже с середины октября. В выходные дни коридор может быть довольно
многолюдным, поэтому если возможность позволяет, стоит прийти сюда в будний день
или ранним утром, ещё до открытия основного потока автобусных туров.

Рядом с озером также расположен небольшой синтоистский храм и несколько
традиционных чайных, где можно попробовать хото — густой суп с лапшой,
типичный для региона Яманаси. Многие путешественники совмещают прогулку по
коридору с поездкой на канатной дороге Кутиномагаи, откуда открывается ещё
один панорамный вид на озеро и гору Фудзи сверху.

Не спешите. Пройдите коридор медленно, от начала до конца, и позвольте
себе просто на несколько минут стать частью этого пейзажа — именно так,
как задумывали его создатели более семидесяти лет назад.
"""


async def main():
    print(f"Generating with voice: {VOICE}")
    # Collapse line wraps/blank lines into single spaces so edge-tts doesn't
    # insert extra pauses at every wrapped or blank line.
    text = " ".join(line.strip() for line in TEXT.strip().splitlines() if line.strip())
    comm = edge_tts.Communicate(text, VOICE)
    await comm.save(OUT)
    print(f"Done -> {OUT}")


if __name__ == "__main__":
    asyncio.run(main())

"""Generate a Russian TTS voice guide for Shinjuku Gyoen (~3 min).
Keep TEXT as continuous flowing sentences with NO blank lines between
paragraphs — edge-tts inserts an audible extra pause at every blank line."""
import asyncio, pathlib, edge_tts

VOICE = "ru-RU-DmitryNeural"

TEXT = (
"Синдзюку Гёэн. Один из самых красивых и разнообразных парков Токио, расположенный всего в нескольких минутах ходьбы от небоскрёбов Синдзюку. "
"Когда-то здесь располагалась резиденция знатной семьи Найто, а в тысяча девятьсот шестом году территория была превращена в императорский сад. "
"Для широкой публики парк открылся в тысяча девятьсот сорок девятом году и с тех пор остаётся одним из любимых мест отдыха токийцев. "
"Уникальность Синдзюку Гёэн в том, что на одной территории соединены три совершенно разных садовых стиля: традиционный японский сад с прудами и мостиками, французский регулярный сад с симметричными аллеями роз, и английский пейзажный сад с широкими лужайками и старыми деревьями. "
"В ноябре парк особенно красив: клёны и гинкго окрашиваются в красные и золотые тона, и это один из лучших моментов в году для прогулки среди осенней листвы. "
"В это же время в парке проходит традиционная выставка хризантем, где можно увидеть искусно выращенные цветы необычных форм. "
"Вход в парк платный, символическая плата около пятисот иен, но она того стоит: несмотря на близость к одному из самых оживлённых районов Токио, внутри царит настоящая тишина. "
"Совет путешественнику: возьмите с собой немного времени, чтобы просто посидеть на скамейке и понаблюдать за сменой пейзажей — здесь легко забыть, что вокруг мегаполис. "
"Синдзюку Гёэн — прекрасное место, чтобы замедлиться и почувствовать спокойствие японской осени перед продолжением дня."
)

async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Shinjuku Gyoen.mp3"
    comm = edge_tts.Communicate(TEXT.strip(), VOICE)
    await comm.save(str(out_path))
    print(f"Saved: {out_path}  ({out_path.stat().st_size / 1024:.0f} KB)")

asyncio.run(main())

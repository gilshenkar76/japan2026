"""Generate a Russian TTS voice guide for Hakone Open-Air Museum (~3 min).
Keep TEXT as continuous flowing sentences with NO blank lines between
paragraphs — edge-tts inserts an audible extra pause at every blank line."""
import asyncio, pathlib, edge_tts

VOICE = "ru-RU-DmitryNeural"

TEXT = (
"Музей под открытым небом Хаконэ. Первый в Японии музей такого рода, открытый в тысяча девятьсот шестьдесят девятом году. "
"Его идея проста и в то же время уникальна: скульптуры современных и классических мастеров выставлены не в закрытых залах, а прямо среди природы, на фоне гор региона Хаконэ. "
"На территории площадью около семидесяти тысяч квадратных метров разместились более ста произведений искусства — работы Родена, Мура, Колдера и многих других всемирно известных скульпторов. "
"Одна из главных достопримечательностей музея — отдельный павильон, посвящённый Пабло Пикассо, где хранится одна из крупнейших в мире коллекций его керамики, картин и гравюр. "
"Гуляя по музею, посетители попадают то в ухоженный сад с лужайками и прудами, то в лес, то на открытую смотровую площадку с видом на окрестные холмы. "
"Есть здесь и специальная секция для детей с интерактивными инсталляциями, а также термальные ножные ванны прямо на свежем воздухе — можно отдохнуть, погрузив ноги в горячую воду, и любоваться скульптурами вокруг. "
"Совет путешественнику: на осмотр всей территории стоит выделить не меньше полутора-двух часов, а удобная обувь здесь особенно важна, так как маршрут включает подъёмы и спуски. "
"Музей под открытым небом Хаконэ — это место, где искусство и природа существуют в идеальной гармонии, и один из лучших способов завершить день среди вулканических пейзажей региона."
)

async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Hakone Open-Air Museum.mp3"
    comm = edge_tts.Communicate(TEXT.strip(), VOICE)
    await comm.save(str(out_path))
    print(f"Saved: {out_path}  ({out_path.stat().st_size / 1024:.0f} KB)")

asyncio.run(main())

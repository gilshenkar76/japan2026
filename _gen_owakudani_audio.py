"""Generate a Russian TTS voice guide for Owakudani (~3 min).
Keep TEXT as continuous flowing sentences with NO blank lines between
paragraphs — edge-tts inserts an audible extra pause at every blank line."""
import asyncio, pathlib, edge_tts

VOICE = "ru-RU-DmitryNeural"

TEXT = (
"Оваку-дани, долина кипящих клубов. Одно из самых необычных мест региона Хаконэ — действующая вулканическая долина, образовавшаяся около трёх тысяч лет назад в результате извержения горы Хаконэ. "
"Название переводится как долина большого кипения, и это очень точное описание: повсюду из земли поднимаются клубы серного пара, а воздух наполнен характерным запахом вулканической активности. "
"Именно здесь готовят знаменитые чёрные яйца, куро тамаго — обычные куриные яйца, сваренные в горячих сернистых источниках. "
"Из-за реакции с минералами в воде скорлупа становится полностью чёрной, а по местному поверью, одно съеденное чёрное яйцо продлевает жизнь на семь лет. "
"Прогулочная тропа вдоль долины ведёт мимо источников и вулканических камней, откуда открывается вид на сам кратер и, в ясную погоду, на гору Фудзи вдалеке. "
"Добраться сюда можно на канатной дороге, идущей прямо над долиной, — это один из немногих способов увидеть вулканическую активность практически без пеших усилий. "
"Совет путешественнику: иногда из-за повышенной сейсмической или газовой активности часть троп временно закрывают в целях безопасности, так что стоит уточнять текущий статус на месте. "
"Оваку-дани напоминает о том, что вся Япония стоит на живой вулканической земле, и это одно из немногих мест, где эту силу природы можно увидеть и почувствовать своими глазами."
)

async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Owakudani.mp3"
    comm = edge_tts.Communicate(TEXT.strip(), VOICE)
    await comm.save(str(out_path))
    print(f"Saved: {out_path}  ({out_path.stat().st_size / 1024:.0f} KB)")

asyncio.run(main())

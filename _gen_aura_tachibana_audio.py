"""Generate a Russian TTS guide for Aura Tachibana ryokan in Hakone-Yumoto."""
import asyncio
import pathlib
import subprocess
import tempfile

import edge_tts
from gtts import gTTS
import imageio_ffmpeg


VOICE = "ru-RU-DmitryNeural"
EDGE_RATE = "+12%"
FALLBACK_TEMPO = "1.14"

TEXT = (
    "Мы оставили шумный Синдзюку позади и приехали в Хаконэ на романскаре. Теперь начинается спокойная часть нашего путешествия. Добро пожаловать в рёкан Аура Татибана. Он стоит на возвышенности над Хаконэ-Юмото, одним из старейших курортных районов Японии. "
    "Рёкан отличается от обычного отеля. Здесь весь вечер построен вокруг тишины, горячего источника и сезонного ужина. При входе следуйте указаниям персонала и снимите уличную обувь там, где начинается чистая зона. В номере вы найдёте юкату, лёгкое хлопковое кимоно. Левую полу запахивают поверх правой и закрепляют поясом. В юкате можно ходить по рёкану, идти в онсэн и приходить на ужин. "
    "Главное здесь, конечно, природная термальная вода Хаконэ-Юмото. Источник прозрачный и слабощелочной. Его показатель пи-аш равен восьми целым семи десятым. Такая вода считается мягкой для кожи. В общественных купальнях есть внутренние ванны, открытые ванны и сауна. Вечером они работают с трёх часов до полуночи. Утром можно прийти с пяти часов до половины десятого. "
    "Перед онсэном оставьте одежду в раздевалке. Купальник здесь не используют. Сначала тщательно вымойтесь в душевой зоне. Затем можно заходить в общую ванну. Маленькое полотенце не опускают в воду. Оставьте его у края или положите на голову. В воде не плавают и разговаривают тихо. Если у вас есть татуировка или медицинские ограничения, заранее уточните правила у стойки регистрации. После купания выпейте воды и немного отдохните. "
    "На верхнем этаже есть три отдельные открытые купальни с видом на горы. Они называются Ано-ю, Уно-ю и Рано-ю. Их бронируют после заселения. Один сеанс длится сорок пять минут и стоит три тысячи триста иен. Особенно приятно попасть туда на закате или вечером. Полотенца нужно взять из номера. "
    "После онсэна нас ждёт японский ужин из нескольких подач. Аура Татибана готовит авторские блюда из сезонных продуктов Хаконэ. Концепция называется Бэппин-рёри. Это означает, что блюдо должно быть красивым и снаружи, и по содержанию. Меню меняется по сезону. Обычно в нём есть небольшие закуски, суп, сашими, рыба или мясо, овощи и десерт. Не торопитесь. Каждая подача является частью общего ритма вечера. Об аллергиях нужно сообщить персоналу заранее. "
    "Уточните время ужина при заселении. Обычно начало назначают между шестью и половиной седьмого, либо между семью и половиной восьмого. Утром будет традиционный японский завтрак. Его подают в половине восьмого, в восемь или в половине девятого. "
    "Сегодня наша задача простая. Переодеться в юкату, отдохнуть в онсэне и спокойно познакомиться с кухней рёкана. Завтра нас ждёт большой день в Хаконэ, озеро Аси, Овакудани и музей под открытым небом. А пока замедлитесь и почувствуйте японский ритм отдыха. Приятного вечера в Аура Татибана."
)


async def main():
    out_dir = pathlib.Path("mp3")
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "Aura Tachibana.mp3"
    try:
        communication = edge_tts.Communicate(TEXT.strip(), VOICE, rate=EDGE_RATE)
        await communication.save(str(out_path))
    except Exception as error:
        print(f"Edge TTS unavailable ({error}); using gTTS fallback")
        with tempfile.TemporaryDirectory() as temp_dir:
            raw_path = pathlib.Path(temp_dir) / "raw.mp3"
            gTTS(TEXT.strip(), lang="ru", slow=False).save(str(raw_path))
            subprocess.run(
                [
                    imageio_ffmpeg.get_ffmpeg_exe(),
                    "-y",
                    "-i",
                    str(raw_path),
                    "-filter:a",
                    f"atempo={FALLBACK_TEMPO}",
                    "-codec:a",
                    "libmp3lame",
                    "-q:a",
                    "4",
                    str(out_path),
                ],
                check=True,
                capture_output=True,
            )
    print(f"Saved: {out_path} ({out_path.stat().st_size / 1024:.0f} KB)")


asyncio.run(main())
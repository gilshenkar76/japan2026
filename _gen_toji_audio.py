"""Professional Russian tour-guide narration for To-ji Temple, Kyoto.
Generates mp3/To-ji Temple.mp3 using edge-tts, ru-RU-DmitryNeural voice, regular speed.
"""
import asyncio
import edge_tts

VOICE = "ru-RU-DmitryNeural"
OUT = "mp3/To-ji Temple.mp3"

TEXT = """
Добро пожаловать в храм То-дзи — один из старейших и самых значимых буддийских
храмов Киото, внесённый в список Всемирного наследия ЮНЕСКО как часть
Исторических памятников древнего Киото.

Немного истории. Храм был основан в семьсот девяносто шестом году, всего через
два года после того, как Киото стал новой столицей Японии под именем Хэйан-кё.
Тогда То-дзи, что означает Восточный храм, вместе с несохранившимся до наших дней
Западным храмом Сай-дзи, стоял по обе стороны от главных городских ворот
и служил официальным духовным стражем, охраняющим въезд в столицу.

Поворотным моментом в истории храма стал восемьсот двадцать третий год, когда
император Сага передал То-дзи знаменитому монаху Кукаю, также известному как
Кобо Дайси — основателю эзотерической школы буддизма Сингон. Именно благодаря ему
храм превратился в главный центр этой традиции в Японии и остаётся им по сей день.

Перед вами возвышается пятиярусная пагода — самое высокое деревянное сооружение
в Японии, её высота составляет около пятидесяти пяти метров. Однако важно знать,
что нынешнее здание — это уже пятая версия пагоды. Предыдущие четыре были
уничтожены пожарами и молниями на протяжении столетий, а ту постройку,
которую вы видите сейчас, возвели в тысяча шестьсот сорок четвёртом году
по приказу третьего сёгуна Токугавы, Иэмицу. Несмотря на многочисленные
перестройки, пагода сохраняет облик и пропорции периода Хэйан.

В главном зале, Кондо, и в зале Кодо хранится одна из самых важных коллекций
буддийской скульптуры в Японии — двадцать одна статуя, расположенная в виде
трёхмерной мандалы. Кукай специально расположил их так, чтобы посетитель мог
буквально пройти сквозь визуальное представление буддийской вселенной,
а не просто разглядывать отдельные фигуры.

Стоит обратить внимание и на спокойные сады вокруг храмовых построек,
а также на пруд перед пагодой — особенно красивый ранним утром, когда
отражение пагоды в воде создаёт одну из самых узнаваемых открыточных
картин Киото.

Если ваш визит приходится на двадцать первое число месяца, у вас есть
уникальная возможность попасть на рынок Кобо-сан — эта традиция восходит
к дню памяти Кукая и проводится на территории храма уже несколько столетий.
Сотни лотков предлагают антиквариат, керамику, кимоно и уличную еду,
и это один из лучших способов увидеть повседневную культуру Киото.

Пройдите немного вперёд, к подножию пагоды, и на мгновение представьте:
этот храм встречал путешественников, паломников и императоров на протяжении
более тысячи двухсот лет — и продолжает делать это сегодня, для вас.
"""


async def main():
    print(f"Generating with voice: {VOICE}")
    # Collapse line wraps/blank lines into single spaces so edge-tts doesn't
    # insert extra pauses at every wrapped or blank line.
    text = " ".join(line.strip() for line in TEXT.strip().splitlines() if line.strip())
    comm = edge_tts.Communicate(text, VOICE)
    await comm.save(OUT)
    print(f"Done -> {OUT}")


if __name__ == "__main__":
    asyncio.run(main())
